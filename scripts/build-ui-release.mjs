import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url)));
const { contractVersion } = JSON.parse(readFileSync(new URL('../contracts/naeil-chrome.v1.json', import.meta.url)));
const output = `// Generated by scripts/build-ui-release.mjs; do not edit.\nexport const uiRelease = { version: ${JSON.stringify(version)}, contractVersion: ${JSON.stringify(contractVersion)} } as const;\n`;
const path = new URL('../src/lib/ui-release.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('UI release metadata drift; run pnpm build:release');
} else writeFileSync(path, output);
