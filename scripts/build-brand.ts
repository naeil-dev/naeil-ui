import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

// Version selection is explicit. Released brand directories remain immutable.
const { version } = JSON.parse(readFileSync("brand/current.json", "utf8")) as { version: string };
assert(/^\d+\.\d+\.\d+$/.test(version), "Invalid brand version");
const root = `brand/naeil/${version}`;
const check = process.argv.includes("--check");
const hashes = new Map(readFileSync(`${root}/SHA256SUMS.txt`, "utf8").trim().split("\n")
  .map(line => { const [hash, file] = line.split("  "); return [file, hash]; }));
function source(file: string) {
  const bytes = readFileSync(`${root}/${file}`);
  assert.equal(createHash("sha256").update(bytes).digest("hex"), hashes.get(file), `Released brand file drift: ${file}`);
  return bytes;
}
function output(file: string, content: string | Buffer) {
  if (check) assert(readFileSync(file).equals(typeof content === "string" ? Buffer.from(content) : content), `Run pnpm build:brand: ${file}`);
  else { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, content); }
}
const modes = ["color", "color-dark", "gray", "gray-dark"];
const forms = ["symbol", "symbol-small", "horizontal", "footer", "stacked", "wordmark"];
const cases: string[] = [];
const dimensions: Record<string, { width: number; height: number; viewBox: string }> = {};
for (const form of forms) {
  for (const mode of [...modes, "mono"]) {
    const kind = form === "symbol-small" ? "symbol" : form;
    const suffix = form === "symbol-small" ? "-small" : "";
    const file = `svg/naeil-${kind}-${mode === "mono" ? "color" : mode}${suffix}.svg`;
    const svg = source(file).toString();
    assert(!/<(?:text|script|image|foreignObject)\b|\bhref=/.test(svg), `Non-vector brand source: ${file}`);
    const key = `${form}-${mode}`;
    const width = Number(svg.match(/\bwidth="([^"]+)"/)![1]);
    const height = Number(svg.match(/\bheight="([^"]+)"/)![1]);
    const viewBox = svg.match(/\bviewBox="([^"]+)"/)![1];
    dimensions[key] = { width, height, viewBox };
    let body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title>[^<]*<\/title>/, "");
    if (mode === "mono") {
      // Legacy one-ink currentColor silhouette. Prefer tone="gray" for islands/tonal detail.
      body = body.replace(/<linearGradient\b[^>]*>[\s\S]*?<\/linearGradient>/g, "")
        .replace(/fill="[^"]+"/g, 'fill="currentColor"');
    }
    body = body.replace(/([a-z]+)-([a-z]+)=/g, (_, a: string, b: string) => `${a}${b[0].toUpperCase()}${b.slice(1)}=`)
      .replace(/id="([^"]+)"/g, (_, name: string) => 'id={`${id}-' + name + '`}')
      .replace(/="url\(#([^\)]+)\)"/g, (_, name: string) => '={`url(#${id}-' + name + ')`}');
    cases.push(`    case ${JSON.stringify(key)}: return <>${body}</>;`);
  }
}
output("src/components/brand-artwork.generated.tsx", `// Generated by pnpm build:brand from brand/naeil/${version}/svg. Do not edit.\n` +
  `// Lato outline provenance: licenses/Lato-OFL.txt. Brand rights remain separate.\n` +
  `export const brandVersion = ${JSON.stringify(version)};\n` +
  `export const brandDimensions = ${JSON.stringify(dimensions, null, 2)} as const;\n` +
  `export type BrandAsset = keyof typeof brandDimensions;\n` +
  `export function BrandArtwork({ asset, id }: { asset: BrandAsset; id: string }) {\n  switch (asset) {\n${cases.join("\n")}\n  }\n}\n`);
output("licenses/Lato-OFL.txt", source("licenses/Lato-OFL.txt"));
// App-owned file conventions; these are not shared package exports.
const favicon = source("icons/favicon.ico");
assert.equal(favicon.readUInt16LE(2), 1, "Expected an ICO image");
assert.equal(favicon.readUInt16LE(4), 3, "Expected 16/32/48 ICO frames");
for (let index = 0; index < 3; index++) {
  const entry = 6 + index * 16;
  const size = [16, 32, 48][index];
  assert.equal(favicon[entry], size);
  assert.equal(favicon[entry + 1], size);
  const offset = favicon.readUInt32LE(entry + 12);
  assert.equal(favicon.subarray(offset + 1, offset + 4).toString(), "PNG");
  assert.equal(favicon[offset + 25], 6, "ICO PNG frames must be RGBA for Next.js");
}
output("src/app/favicon.ico", favicon);
output("src/app/icon.svg", source("icons/favicon.svg"));
output("src/app/apple-icon.png", source("icons/apple-touch-icon.png"));
console.log(`Brand ${version}: ${check ? "verified" : "generated"} React artwork, font notice and site icons`);
