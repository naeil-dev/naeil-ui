/** One public stylesheet with unchanged, package-local build assets. */
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
const require = createRequire(import.meta.url);
const check = process.argv.includes("--check");
const destination = "src/styles/fonts.css";
const assets = new Map<string, Buffer>();
function fontCSS(entry: string, name: string) {
  const source = require.resolve(entry);
  return readFileSync(source, "utf8").replace(/url\(([^)]+)\)/g, (_, path: string) => {
    const original = resolve(dirname(source), path);
    const target = `dist/fonts/${name}/${basename(original)}`;
    assets.set(target, readFileSync(original));
    // A relative URL works in Next webpack/Turbopack and Vite without a host alias.
    return `url(../../${target})`;
  });
}
const pretendardPath = "pretendard/dist/web/variable/pretendardvariable-dynamic-subset.css";
const pretendard = fontCSS(pretendardPath, "pretendard");
const japanese = fontCSS("@fontsource-variable/noto-sans-jp/wght.css", "noto-sans-jp")
  .replaceAll("'Noto Sans JP Variable'", "'Noto Sans JP'");
// Reuse each original subset's bytes under a Latin-only face, intersecting its
// real coverage with the contract. A full Pretendard font is unnecessary.
const latin = [...pretendard.matchAll(/@font-face\s*\{[^}]+\}/g)].flatMap(([face]) => {
  const range = face.match(/unicode-range:\s*([^;]+);/)![1];
  const intersections = range.split(",").flatMap(part => {
    const [from, to = from] = part.trim().replace(/^U\+/i, "").split("-").map(n => parseInt(n, 16));
    return [[0x20, 0x7e], [0xa0, 0xff]].flatMap(([a, b]) => {
      const start = Math.max(from, a), end = Math.min(to, b);
      return start <= end ? [`U+${start.toString(16)}${start === end ? "" : `-${end.toString(16)}`}`] : [];
    });
  });
  return intersections.length ? [face.replace("'Pretendard Variable'", "'Pretendard Latin'").replace(/unicode-range:[^;]+;/, `unicode-range: ${intersections.join(", ")};`)] : [];
}).join("\n");
const css = `/* Generated by scripts/build-fonts.ts — DO NOT EDIT.
   Pretendard 1.3.9; Noto Sans JP variable 5.3.0. OFL notices ship in licenses/. */
${pretendard}\n${japanese}\n/* Latin-only alias for Japanese stacks. */\n${latin}\n`;
for (const [path, bytes] of assets) {
  if (check) {
    if (!readFileSync(path).equals(bytes)) throw new Error(`${path} has drifted; run pnpm build:fonts`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, bytes);
  }
}
if (check) {
  if (readFileSync(destination, "utf8") !== css) throw new Error("fonts.css is out of date; run pnpm build:fonts");
} else writeFileSync(destination, css);
